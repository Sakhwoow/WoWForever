-- Forever (Classic 1.60): русские тексты, макросы пола.
-- В двух ранее выложенных текстах окончание было записано как «готов$g::а;» — в клиенте так получается лишняя двоеточие.
-- Приводим к виду, который использует официальный русский клиент: целое слово $Gготов:готова;. Можно запускать повторно.

UPDATE `trainer_locale` SET `Greeting_lang` = REPLACE(`Greeting_lang`, 'готов$g::а;', '$gготов:готова;')
WHERE `locale` = 'ruRU' AND `Greeting_lang` LIKE '%$g::а;%';
